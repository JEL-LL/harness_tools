"""Check and map the [[links]] between concordance notes.

Notes are read with priority.load_notes(), so generated files such as INDEX.md
(names starting uppercase or '_') are never treated as notes. Notes being written
by another session at the same time are read as they are; a half-written one just
shows up as a parse error until it is finished.

Usage:
  python links.py [check]          broken links, duplicate slugs, bad front matter,
                                   tracked notes that can never age; exit 1 on broken
                                   links or parse errors
  python links.py backlinks SLUG   notes that link to SLUG
  python links.py index            regenerate concordance/INDEX.md
  python links.py orphans          notes with no links in or out
"""
import argparse, collections, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import config
import priority

INDEX = os.path.join(priority.CONCORDANCE, "INDEX.md")
TOP_LINKED = 15
SUMMARY_LEN = 100


def rel(path):
    """Path relative to the harness root; absolute when it lies elsewhere (e.g. another drive)."""
    try:
        r = os.path.relpath(path, priority.HARNESS)
    except ValueError:  # Windows: different drive
        return path.replace(os.sep, "/")
    return (path if r.startswith("..") else r).replace(os.sep, "/")


def backlinks(notes):
    back = collections.defaultdict(set)
    for s, n in notes.items():
        for t in n["links"]:
            back[t].add(s)
    return back


def duplicates():
    by_slug = collections.defaultdict(list)
    for p in priority.note_paths():
        by_slug[os.path.splitext(os.path.basename(p))[0]].append(p)
    return {s: ps for s, ps in by_slug.items() if len(ps) > 1}


def summary(body):
    for line in body.splitlines():
        line = line.strip()
        if line and not line.startswith("#") and line != "---":
            line = re.sub(r"\[\[([^\]|#]+)[^\]]*\]\]", r"\1", line)
            if len(line) > SUMMARY_LEN:
                line = line[:SUMMARY_LEN].rsplit(" ", 1)[0] + " ..."
            return line
    return ""


def can_age(n):
    """True when something gives the note a last-touched date (see priority.own_score)."""
    meta = n["meta"]
    if meta.get("last_touched"):
        return True
    if meta.get("mentions") and config.thought_log_enabled():
        return True
    return config.COUNT_LOG_ENTRIES and priority.last_log_entry(n) is not None


def problems(notes, errors):
    """Everything `check` reports, as data: broken (slug, target) pairs, parse errors, duplicate slugs,
    untyped notes, ageless notes (state but nothing to age from)."""
    return {
        "broken": sorted((s, t) for s, n in notes.items() for t in n["links"] if t not in notes),
        "errors": sorted(errors),
        "duplicates": duplicates(),
        "untyped": sorted(s for s, n in notes.items() if not n["meta"].get("type")),
        "ageless": sorted(s for s, n in notes.items() if n["meta"].get("state") and not can_age(n)),
    }


def check(notes, errors):
    p = problems(notes, errors)
    broken, dups, untyped, ageless = p["broken"], p["duplicates"], p["untyped"], p["ageless"]
    if broken:
        print("Broken links:")
        for s, t in broken:
            print(f"  [[{t}]]  in {rel(notes[s]['path'])}")
    if errors:
        print("Front matter failed to parse:")
        for path, msg in p["errors"]:
            print(f"  {rel(path)}: {msg}")
    if dups:
        print("Duplicate slugs:")
        for s, ps in sorted(dups.items()):
            print(f"  {s}: {', '.join(rel(x) for x in ps)}")
    if untyped:
        print("No type:", ", ".join(untyped))
    if ageless:
        what = "no mentions or last_touched" if config.thought_log_enabled() else "nothing to age from"
        print(f"state but {what} (never ages):", ", ".join(ageless))
    print(f"{len(notes)} notes, {len(broken)} broken links, {len(errors)} parse errors, "
          f"{len(dups)} duplicate slugs, {len(untyped)} untyped, {len(ageless)} ageless")
    return 1 if broken or errors else 0


def index(notes):
    back = backlinks(notes)
    groups = collections.defaultdict(list)
    for s, n in notes.items():
        groups[str(n["meta"].get("type") or "untyped")].append(s)
    out = ["# Concordance index", "",
           "Generated by `scripts/links.py index`; do not edit by hand.", ""]
    for t in sorted(groups):
        out += [f"## {t}", ""]
        for s in sorted(groups[t]):
            n = notes[s]
            line = f"- [[{s}]] — {summary(n['body'])}"
            if n["meta"].get("state"):
                line += f" ({n['meta']['state']})"
            out.append(line)
        out.append("")
    top = sorted(((len(v), s) for s, v in back.items() if s in notes), key=lambda x: (-x[0], x[1]))
    out += ["## Most linked", ""] + [f"- [[{s}]] — {c}" for c, s in top[:TOP_LINKED]] + [""]
    tmp = INDEX + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    os.replace(tmp, INDEX)
    print(f"wrote {rel(INDEX)}: {len(notes)} notes in {len(groups)} types")


def main():
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", nargs="?", default="check", choices=["check", "backlinks", "index", "orphans"])
    ap.add_argument("slug", nargs="?")
    a = ap.parse_args()
    if not os.path.isdir(priority.CONCORDANCE):
        sys.exit(f"no concordance folder at {priority.CONCORDANCE} (set HARNESS_ROOT or run inside a harness)")
    errors = []
    notes = priority.load_notes(errors)
    if a.cmd == "check":
        sys.exit(check(notes, errors))
    if a.cmd == "backlinks":
        if not a.slug:
            sys.exit("backlinks needs a SLUG")
        for s in sorted(backlinks(notes).get(a.slug, ())):
            print(f"{s:34} {rel(notes[s]['path'])}")
        if a.slug not in notes:
            print(f"(no note named {a.slug})", file=sys.stderr)
    elif a.cmd == "index":
        index(notes)
    elif a.cmd == "orphans":
        linked = set(backlinks(notes))
        for s in sorted(s for s, n in notes.items() if not n["links"] and s not in linked):
            print(f"{s:34} {rel(notes[s]['path'])}")


if __name__ == "__main__":
    main()
